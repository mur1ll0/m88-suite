def crc8(data: bytes, crc: int = 0xFF) -> int:
    for b in data:
        crc = _CRC8[(crc ^ b) & 0xFF]
    return crc


class Packer:
    def __init__(self):
        self.seq = 0
        self.t0 = time.time()

    def pack(self, payload: bytes) -> bytes:
        self.seq = (self.seq + 1) & 0xFFFF
        ms = int((time.time() - self.t0) * 1000) & 0xFFFFFFFF
        return HEAD.pack(MAGIC, FLAG_CRC, ms, self.seq, len(payload), crc8(payload)) + payload


def command(opcode: int, param: int = 0, payload: bytes = b"") -> bytes:
    return struct.pack("<IIH", opcode, param, len(payload)) + payload


def camera_on_payload(width: int, height: int, fmt: int, protocol: int, rotate: int = 0) -> bytes:
    return struct.pack("<HHHHH", width, height, fmt, protocol, rotate)


class Unpacker:
    """Remonta frames db_trans_head_t de um fluxo TCP."""

    def __init__(self):
        self.buf = b""

    def feed(self, data: bytes):
        self.buf += data
        out = []
        while len(self.buf) >= HEAD.size:
            magic, flags, ts, seq, length, crc = HEAD.unpack_from(self.buf)
            if magic != MAGIC:
                i = self.buf.find(struct.pack("<H", MAGIC), 1)
                self.buf = self.buf[i:] if i > 0 else b""
                continue
            if len(self.buf) < HEAD.size + length:
                break
            payload = self.buf[HEAD.size:HEAD.size + length]
            self.buf = self.buf[HEAD.size + length:]
            ok = not (flags & FLAG_CRC) or crc8(payload) == crc
            out.append({"flags": flags, "ts": ts, "seq": seq, "payload": payload, "crc_ok": ok})
        return out


def parse_event(payload: bytes) -> dict:
    """db_evt_head_t = opcode u32 | status u8 | flags u16 | length u16 | payload."""
    opcode, status, flags, length = struct.unpack_from("<IBHH", payload)
    return {"opcode": opcode, "status": status, "flags": flags, "data": payload[9:9 + length]}
