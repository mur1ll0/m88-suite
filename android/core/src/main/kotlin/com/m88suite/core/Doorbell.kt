    fun crc8(data: ByteArray, from: Int = 0, to: Int = data.size): Int {
        var crc = 0xFF
        for (i in from until to) crc = CRC8[(crc xor (data[i].toInt() and 0xFF)) and 0xFF]
        return crc
    }

    class Packer {
        private var seq = 0
        private val t0 = System.currentTimeMillis()

        fun pack(payload: ByteArray): ByteArray {
            seq = (seq + 1) and 0xFFFF
            val buf = ByteBuffer.allocate(HEAD_SIZE + payload.size).order(ByteOrder.LITTLE_ENDIAN)
            buf.putShort(MAGIC.toShort()).putShort(FLAG_CRC.toShort())
                .putInt((System.currentTimeMillis() - t0).toInt()).putShort(seq.toShort())
                .putShort(payload.size.toShort()).put(crc8(payload).toByte()).put(ByteArray(3)).put(payload)
            return buf.array()
        }
    }

    fun command(opcode: Int, param: Int = 0, payload: ByteArray = ByteArray(0)): ByteArray =
        ByteBuffer.allocate(10 + payload.size).order(ByteOrder.LITTLE_ENDIAN)
            .putInt(opcode).putInt(param).putShort(payload.size.toShort()).put(payload).array()

    fun cameraOnPayload(width: Int, height: Int, format: Int, protocol: Int = 0, rotate: Int = 0): ByteArray =
        ByteBuffer.allocate(10).order(ByteOrder.LITTLE_ENDIAN).putShort(width.toShort()).putShort(height.toShort())
            .putShort(format.toShort()).putShort(protocol.toShort()).putShort(rotate.toShort()).array()

    data class Packet(val flags: Int, val seq: Int, val payload: ByteArray, val crcOk: Boolean)

    /** Remonta pacotes de um fluxo TCP (ou de um datagrama UDP isolado). */
    class Unpacker {
        private var buf = ByteArray(0)

        fun feed(data: ByteArray): List<Packet> {
            buf += data
            val out = mutableListOf<Packet>()
            while (buf.size >= HEAD_SIZE) {
                val b = ByteBuffer.wrap(buf).order(ByteOrder.LITTLE_ENDIAN)
                if (b.getShort(0).toInt() and 0xFFFF != MAGIC) {
                    val next = (1 until buf.size - 1).firstOrNull {
                        (buf[it].toInt() and 0xFF) == 0xD5 && (buf[it + 1].toInt() and 0xFF) == 0xF0
                    }
                    buf = if (next != null) buf.copyOfRange(next, buf.size) else ByteArray(0)
                    continue
                }
                val flags = b.getShort(2).toInt() and 0xFFFF
                val seq = b.getShort(8).toInt() and 0xFFFF
                val len = b.getShort(10).toInt() and 0xFFFF
                val crc = buf[12].toInt() and 0xFF
                if (buf.size < HEAD_SIZE + len) break
                val payload = buf.copyOfRange(HEAD_SIZE, HEAD_SIZE + len)
                buf = buf.copyOfRange(HEAD_SIZE + len, buf.size)
                out += Packet(flags, seq, payload, flags and FLAG_CRC == 0 || crc8(payload) == crc)
            }
            return out
        }
    }
